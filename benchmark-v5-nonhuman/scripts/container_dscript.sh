#!/usr/bin/env bash
set -euo pipefail
BENCH_ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
BENCH_PROJECT=$(dirname "$BENCH_ROOT")
BENCH_EXTERNAL=$(dirname "$BENCH_PROJECT")/iPIN-OpenPPI
exec env -u APPTAINER_BIND -u APPTAINER_BINDPATH -u SINGULARITY_BIND -u SINGULARITY_BINDPATH \
 APPTAINERENV_CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-0}" \
 apptainer exec --nv --cleanenv --no-home --no-mount bind-paths,home,cwd,hostfs \
 --bind "$BENCH_PROJECT:$BENCH_PROJECT:ro" --bind "$BENCH_ROOT:$BENCH_ROOT:rw" \
 --bind "$BENCH_EXTERNAL:$BENCH_EXTERNAL:ro" --pwd "$BENCH_ROOT" \
 --env "PYTHONPATH=$BENCH_ROOT/scripts,PYTHONDONTWRITEBYTECODE=1,PYTHONUNBUFFERED=1,SLURM_JOB_ID=${SLURM_JOB_ID:-local},HF_HOME=$BENCH_ROOT/cache/dscript,HF_HUB_OFFLINE=1,TRANSFORMERS_OFFLINE=1,OMP_NUM_THREADS=8,MKL_NUM_THREADS=8,OPENBLAS_NUM_THREADS=8,TOKENIZERS_PARALLELISM=false,CUBLAS_WORKSPACE_CONFIG=:4096:8,NVIDIA_TF32_OVERRIDE=0,MPLCONFIGDIR=$BENCH_ROOT/cache/dscript/matplotlib" \
 "$BENCH_EXTERNAL/benchmark/containers/images/dscript-native-arm64-v1.sif" "$@"
