BENCH_ROOT=/nobackup/proj/disk/theo-storage/personal/jalil/iPIN/benchmark-v4
BENCH_WORKSPACE=$(dirname "$BENCH_ROOT")
BENCH_IMAGE="$BENCH_WORKSPACE/images/plm-interact-esmc/plm-interact-esmc-arm64-v1.sif"
BENCH_IMAGE_HASH=ed6aeac781502090632bc2a705300b161b6a65ccfbcf6c7cf64d8d61d8e5b5ef
