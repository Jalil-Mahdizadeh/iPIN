"""Common full-length forward path matching the cached native and v1 benchmark."""
import hashlib
import json
import os
from pathlib import Path

import numpy as np
import torch

from frozen_data import PairData
from frozen_model import PairModel

ROOT = Path(__file__).resolve().parents[1]


def sha256(path):
    digest = hashlib.sha256()
    with open(path, 'rb') as handle:
        for block in iter(lambda: handle.read(16 * 1024 ** 2), b''):
            digest.update(block)
    return digest.hexdigest()


def atomic_json(path, value):
    path = Path(path)
    temporary = path.with_name(path.name + f'.tmp-{os.getpid()}')
    with temporary.open('w') as handle:
        json.dump(value, handle, indent=2, allow_nan=False)
        handle.write('\n')
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temporary, path)


def configure(local_rank=0):
    torch.cuda.set_device(local_rank)
    torch.set_num_threads(8)
    torch.manual_seed(20260929)
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    torch.backends.cudnn.benchmark = False
    torch.backends.cudnn.deterministic = True
    torch.use_deterministic_algorithms(True)
    return torch.device('cuda', local_rank)


def load_model(name, device, backend='efficient'):
    selection = json.loads((ROOT / 'provenance/selection.json').read_text())
    entry = selection['models'][name]
    path = ROOT / entry['path']
    assert sha256(path) == entry['sha256'], (name, 'checkpoint hash mismatch')
    # Local training checkpoints were generated by us and are hash-verified.
    saved = torch.load(path, map_location='cpu', mmap=True,
                       weights_only=entry['kind'] == 'released_state_dict')
    state = saved if entry['kind'] == 'released_state_dict' else saved['model']
    if entry['kind'] != 'released_state_dict':
        assert saved['training_state']['update'] == entry['update']
        assert saved['fingerprint'] == entry['source_manifest']['fingerprint']
    model = PairModel(selection['base_model_path'], mode='reference', backend=backend)
    model.load_state_dict(state, strict=True)
    assert all(torch.equal(value, state[key]) for key, value in model.state_dict().items())
    model.esm_mask.gradient_checkpointing_disable()
    model.eval().requires_grad_(False).to(device)
    assert all(p.dtype == torch.float32 for p in model.parameters())
    return model


@torch.inference_mode()
def predict(model, data, indices, device, bf16=True):
    features = data.batch(indices, 0, 2, False, device)
    assert features['attention_mask'].sum(1).cpu().tolist() == [
        int(data.lengths[i]) for i in indices for _ in range(2)]
    with torch.autocast('cuda', dtype=torch.bfloat16, enabled=bf16):
        scores = model(features['input_ids'], features['attention_mask'])
    scores = scores.float().cpu().numpy().astype(np.float64)
    assert scores.shape == (len(indices), 2) and np.isfinite(scores).all()
    return np.column_stack((indices, data.rows[indices, 2], scores))


def prediction_fingerprint():
    files = ['config.json', 'provenance/selection.json']
    files += [f'scripts/{name}' for name in ('common.py', 'infer.py', 'frozen_data.py', 'frozen_model.py', 'container.sh')]
    return hashlib.sha256(json.dumps({name: sha256(ROOT / name) for name in files},
                                    sort_keys=True).encode()).hexdigest()
